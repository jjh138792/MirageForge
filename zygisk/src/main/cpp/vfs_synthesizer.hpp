// 根据 RuntimeProfile 预合成所有虚拟硬件节点文本
inline void synthesize_vfs_nodes() {
    // 1. 合成虚拟 build.prop
    {
        std::ostringstream ss;
        ss << "# Generated by MirageForge v3.0 VFS Engine\n";
        for (const auto &kv : g_profile.prop_map) {
            ss << kv.first << "=" << kv.second << "\n";
        }
        g_profile.vfs_build_prop = ss.str();
    }

    // 2. 合成虚拟 /proc/cpuinfo
    {
        std::ostringstream ss;
        int cores = (g_profile.cpu_cores > 0 && g_profile.cpu_cores <= 16) ? g_profile.cpu_cores : 8;
        std::string hw = g_profile.cpu_hardware.empty() ? "Qualcomm Technologies, Inc SM8750" : g_profile.cpu_hardware;
        ss << "Processor\t: AArch64 Processor rev 1 (aarch64)\n";
        for (int i = 0; i < cores; ++i) {
            ss << "processor\t: " << i << "\n";
            ss << "BogoMIPS\t: 38.40\n";
            ss << "Features\t: fp asimd evtstrm aes pmull sha1 sha2 crc32 atomics fphp asimdhp cpuid asimdrdm jscvt fcma lrcpc dcpop sha3 sm3 sm4 asimddp sha512 sve asimdfhm dit uscat ilrcpc flagm ssbs sb paca pacg dcpodp sve2 sveaes svepmull svebitperm svesha3 svesm4 flagm2 frint svei8mm svebf16 i8mm bf16 dgh bti\n";
            ss << "CPU implementer\t: 0x41\n";
            ss << "CPU architecture: 8\n";
            ss << "CPU variant\t: 0x1\n";
            ss << "CPU part\t: " << (i < 6 ? "0xd85" : "0xd87") << "\n";
            ss << "CPU revision\t: 1\n\n";
        }
        ss << "Hardware\t: " << hw << "\n";
        g_profile.vfs_cpuinfo = ss.str();
    }

    // 3. 合成虚拟 /proc/meminfo
    {
        long total_kb = static_cast<long>(g_profile.ram_gb > 0 ? g_profile.ram_gb : 16) * 1024L * 1024L;
        long free_kb = total_kb * 35 / 100;
        long avail_kb = total_kb * 62 / 100;
        std::ostringstream ss;
        ss << "MemTotal:       " << total_kb << " kB\n"
           << "MemFree:        " << free_kb << " kB\n"
           << "MemAvailable:   " << avail_kb << " kB\n"
           << "Buffers:          142680 kB\n"
           << "Cached:          3842100 kB\n"
           << "SwapTotal:       8388604 kB\n"
           << "SwapFree:        7912400 kB\n";
        g_profile.vfs_meminfo = ss.str();
    }

    // 4. 合成虚拟 /proc/version
    {
        if (!g_profile.kernel_version.empty()) {
            g_profile.vfs_proc_version = g_profile.kernel_version + "\n";
        } else {
            g_profile.vfs_proc_version = "Linux version 6.6.30-android15-8-g94b8f12ab4c1 (build-user@build-host) (Android (11368308, +pgo, +bolt, +lto, +mlgo, based on r510928) clang version 18.0.0) #1 SMP PREEMPT Fri Nov 15 12:00:00 UTC 2025\n";
        }
    }

    // 5. 合成虚拟 GPU 节点 (/sys/class/kgsl/kgsl-3d0/gpu_model)
    {
        std::string gpu = g_profile.gl_renderer.empty() ? "Adreno830" : g_profile.gl_renderer;
        g_profile.vfs_gpu_model = gpu + "\n";
    }
}

// 匹配被访问路径并返回对应的虚拟内容指针
inline const std::string *match_vfs_virtual_content(const char *path) {
    if (!path || !g_profile.enable_vfs_shield) return nullptr;

    if (strcmp(path, "/system/build.prop") == 0 ||
        strcmp(path, "/system/etc/build.prop") == 0 ||
        strcmp(path, "/vendor/build.prop") == 0 ||
        strcmp(path, "/product/build.prop") == 0 ||
        strcmp(path, "/product/etc/build.prop") == 0 ||
        strcmp(path, "/odm/etc/build.prop") == 0) {
        record_probe_event("VFS", path, "Spoofed build.prop");
        return &g_profile.vfs_build_prop;
    }

    if (strcmp(path, "/proc/cpuinfo") == 0) {
        record_probe_event("VFS", path, g_profile.cpu_hardware);
        return &g_profile.vfs_cpuinfo;
    }

    if (strcmp(path, "/proc/meminfo") == 0 && g_profile.ram_gb > 0) {
        record_probe_event("VFS", path, std::to_string(g_profile.ram_gb) + "GB RAM");
        return &g_profile.vfs_meminfo;
    }

    if (strcmp(path, "/proc/version") == 0 && !g_profile.vfs_proc_version.empty()) {
        record_probe_event("VFS", path, "Spoofed Kernel Banner");
        return &g_profile.vfs_proc_version;
    }

    if (strcmp(path, "/sys/class/kgsl/kgsl-3d0/gpu_model") == 0 ||
        strcmp(path, "/sys/devices/soc0/machine") == 0) {
        record_probe_event("VFS", path, g_profile.vfs_gpu_model);
        return &g_profile.vfs_gpu_model;
    }

    return nullptr;
}

inline int create_memfd_from_string(const std::string &content) {
    int fd = static_cast<int>(syscall(__NR_memfd_create, "mirage_vfs", MFD_CLOEXEC));
    if (fd < 0) return -1;
    if (!content.empty()) {
        write_exact(fd, content.data(), content.size());
        lseek(fd, 0, SEEK_SET);
    }
    return fd;
}

inline int hook_openat(int dirfd, const char *pathname, int flags, mode_t mode) {
    if (const std::string *content = match_vfs_virtual_content(pathname)) {
        int fake_fd = create_memfd_from_string(*content);
        if (fake_fd >= 0) return fake_fd;
    }
    return orig_openat ? orig_openat(dirfd, pathname, flags, mode) : -1;
}

inline int hook_openat_2(int dirfd, const char *pathname, int flags) {
    if (const std::string *content = match_vfs_virtual_content(pathname)) {
        int fake_fd = create_memfd_from_string(*content);
        if (fake_fd >= 0) return fake_fd;
    }
    return orig_openat_2 ? orig_openat_2(dirfd, pathname, flags) : -1;
}

inline int hook_open(const char *pathname, int flags, mode_t mode) {
    if (const std::string *content = match_vfs_virtual_content(pathname)) {
        int fake_fd = create_memfd_from_string(*content);
        if (fake_fd >= 0) return fake_fd;
    }
    return orig_open ? orig_open(pathname, flags, mode) : -1;
}

inline FILE *hook_fopen(const char *pathname, const char *mode) {
    if (const std::string *content = match_vfs_virtual_content(pathname)) {
        int fake_fd = create_memfd_from_string(*content);
        if (fake_fd >= 0) {
            FILE *fp = fdopen(fake_fd, "r");
            if (fp) return fp;
            close(fake_fd);
        }
    }
    return orig_fopen ? orig_fopen(pathname, mode) : nullptr;
}

